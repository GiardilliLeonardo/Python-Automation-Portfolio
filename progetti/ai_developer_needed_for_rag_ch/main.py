# 3. MODEL CONTEXT PROTOCOL (MCP) INTERFACE
# ==========================================
@dataclass
class MCPTool:
    name: str
    description: str
    parameters: Dict[str, Any]
    handler: Callable[..., Any]


class MCPEndpoint:
    """Simulates an MCP (Model Context Protocol) runtime host."""
    def __init__(self):
        self._registry: Dict[str, MCPTool] = {}

    def register_tool(self, name: str, description: str, parameters: Dict[str, Any], handler: Callable):
        self._registry[name] = MCPTool(name, description, parameters, handler)

    def list_tools(self) -> List[Dict[str, Any]]:
        return [
            {
                "name": tool.name,
                "description": tool.description,
                "input_schema": tool.parameters,
            }
            for tool in self._registry.values()
        ]

    def call_tool(self, name: str, arguments: Dict[str, Any]) -> Any:
        if name not in self._registry:
            raise KeyError(f"Tool {name} is not registered under MCP host.")
        return self._registry[name].handler(**arguments)


