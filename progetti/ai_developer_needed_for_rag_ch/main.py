@dataclass
class Document:
    page_content: str
    metadata: Dict[str, Any] = field(default_factory=dict)
    embedding: Optional[np.ndarray] = None


class SimpleVectorStore:
    """Lightweight in-memory vector store using cosine similarity."""
    def __init__(self, dimension: int = 1536):
        self.dimension = dimension
        self.documents: List[Document] = []

    def _mock_embedding(self, text: str) -> np.ndarray:
        seed = sum(ord(c) for c in text) % (2**32)
        rng = np.random.default_rng(seed)
        vec = rng.standard_normal(self.dimension)
        return vec / np.linalg.norm(vec)

    def add_documents(self, docs: List[Document]) -> None:
        for doc in docs:
            if doc.embedding is None:
                doc.embedding = self._mock_embedding(doc.page_content)
            self.documents.append(doc)

    def similarity_search(self, query: str, top_k: int = 2) -> List[Document]:
        if not self.documents:
            return []
        query_vec = self._mock_embedding(query)
        doc_embeddings = np.array([doc.embedding for doc in self.documents])
        similarities = np.dot(doc_embeddings, query_vec)
        top_indices = np.argsort(similarities)[::-1][:top_k]
        return [self.documents[i] for i in top_indices]


